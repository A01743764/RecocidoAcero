import numpy as np
import matplotlib.pyplot as plt

# ===== GRADOS REALES INDICADOS POR TERNIUM; PROPIEDADES BIBLIOGRAFICAS =====
# Valores representativos constantes alrededor de 400 C; NO medidos por Ternium.
ACEROS = {
    'SAE 1006': dict(rho=7733.0, cp=615.0, ks=42.7),
    'SAE 1010': dict(rho=7870.0, cp=590.0, ks=46.0),
}

# ===== REGISTRO DE REFERENCIA DEL EXCEL Y DATOS ADICIONALES DE TERNIUM =====
MATERIAL_REFERENCIA, FAMILIA_REFERENCIA, GRADO_REFERENCIA = 'DFH051001', 'CS', 'TX2145'
MASA_REFERENCIA_KG = 15173.0  # Excel Hoja2 M3; informativo
TEMP_SAT_EXCEL_F = 1247.0     # Excel Hoja2 W3; objetivo, NO gas ni punto frio medido
TIEMPO_SAT_EXCEL_MIN = 479.9  # Excel Hoja2 X3; otra etapa, no calentamiento
TEMP_HORNO_PROGRAMADA_F = 1650.0  # Ternium, no equivale a gas(t)
TEMP_SAT_GAS_F = 1265.0            # Ternium; gas fuera del contacto
TEMP_CONTACTO_F = 1175.0           # Ternium; dato aislado del primer rollo
DISTANCIA_CONTACTO_DESDE_DI_M = 25.0 * 0.0254
DIAMETRO_CAMPANA = 2.451    # m; no es D_HIDRAULICO
ALTURA_OPERACION = 5.250    # m; no es L_FLUJO
CAUDAL_TOTAL_M3_S = 52000.0 * 0.028316846592 / 60.0

# Geometria combinada de un rollo ilustrativo: diámetro exterior MAXIMO, no medido en fila 3.
DIAMETRO_INTERIOR = 0.508  # m; Ternium
DIAMETRO_EXTERIOR = 1.829  # m; MAXIMO Ternium (hipotesis de caso geometrico)
ALTURA = 1.215             # m; Excel K3, ancho del rollo TX2145, NO asignado a SAE
ESPESOR_LAMINA = 0.00156   # m; Excel L3, idem

# Condiciones de frontera: la curva completa del gas NO se entrego.
T_INICIAL = 25.0   # C, SUPUESTO
T_GAS_MAX = (TEMP_SAT_GAS_F-32.0)*5.0/9.0  # 685 C; Ternium para gas SIN contacto;
                                           # usarla como frontera constante es SUPUESTO
SUBIDA_GAS_H = 12.0  # h, SUPUESTO de rampa lineal
OBJETIVO = (TEMP_SAT_EXCEL_F-32.0)*5.0/9.0  # 675 C; Excel, solo umbral de grafica
OBJETIVOS = np.array([580., 600., 625., 650., 665., OBJETIVO])
assert np.all(OBJETIVOS < T_GAS_MAX), 'La temperatura objetivo debe ser inferior a la meseta del gas.'

# Discretizacion, sin cambio en el metodo de solucion.
DURACION_H = 60.0  # horizonte numerico para alcanzar 675 C cerca de la meseta
NR, NZ, DT = 18, 20, 10.0  # celdas radial/axial y paso explicito (s)

# Correlacion de referencia: ninguno de estos valores de contacto/gas es medicion Ternium.
P_MPA = 8.0            # MPa, valor de referencia de literatura, no presion del rollo
H_MPA = 1133.86        # MPa, referencia de literatura, no ensayo Ternium
RUGOSIDAD = 3.2215e-6  # m, referencia de literatura; Ternium no reporto rugosidad
EMISIVIDAD = 0.08554   # referencia de literatura
K_OXIDO = 3.0          # W/(m K), SUPUESTO
TAN_THETA = 0.1        # SUPUESTO
ETA_EMULSION = 0.7    # SUPUESTO
XI_RADIACION = 1.2    # SUPUESTO
PSI_VORTICE = 1.0     # SUPUESTO
VELOCIDAD_GAS = 5.0   # m/s, SUPUESTO; no derivable del caudal global sin area/reparto
D_HIDRAULICO = 0.15   # m, SUPUESTO; no equivale al diametro de campana
L_FLUJO = 1.5         # m, SUPUESTO; no equivale a la altura de operacion
K_GAS = 0.20          # W/(m K), SUPUESTO de hidrogeno constante
MU_GAS = 1.1e-5       # Pa s, SUPUESTO constante
RHO_GAS = 0.09        # kg/m3, SUPUESTO constante
SIGMA = 5.670374419e-8


def gas(t):
    return T_INICIAL + (T_GAS_MAX-T_INICIAL)*min(t/(SUBIDA_GAS_H*3600), 1.)


def conveccion(Tg_c):
    """Ecuaciones (7)-(8): Dittus-Boelter corregida + factor radiativo."""
    h = (0.023*PSI_VORTICE*VELOCIDAD_GAS**0.8 /
         D_HIDRAULICO**0.2 * (MU_GAS/RHO_GAS)**(-0.8) * K_GAS *
         (1+(D_HIDRAULICO/L_FLUJO)**0.7))
    return h if Tg_c+273.15 < 800 else XI_RADIACION*h


def radial_efectiva(ks, T_c, Tg_c):
    """Red de resistencias (9)-(17); evaluada con temperatura media de celda.
    Para Tg<800 K se usa eta de la expresion (17) del paper.
    """
    tm = np.asarray(T_c)+273.15  # K para radiacion
    phi = P_MPA/(H_MPA+P_MPA)  # ecuacion (14)
    b = 42.7e-6*np.exp(-0.05*P_MPA)  # ecuacion (15); P en MPa
    ro = 10e-6/K_OXIDO
    rr = (2-EMISIVIDAD)/(4*(1-phi)*EMISIVIDAD*SIGMA*tm**3)
    rg = b/((1-phi)*K_GAS)
    rd = RUGOSIDAD/(1.13*ks*TAN_THETA)*phi**(-0.94)
    r_par = 1/(1/rr + 1/rg + 1/rd)
    r_acero = ESPESOR_LAMINA/ks
    if Tg_c+273.15 < 800:
        return ETA_EMULSION*(ESPESOR_LAMINA+b)/(r_acero+r_par)
    return (ESPESOR_LAMINA+b+10e-6)/(r_acero+ro+r_par)


def simular(acero):
    rho, cp, ks = acero['rho'], acero['cp'], acero['ks']
    ri, re = DIAMETRO_INTERIOR/2, DIAMETRO_EXTERIOR/2
    r = np.linspace(ri, re, NR+1)
    dr, dz = (re-ri)/NR, ALTURA/NZ
    areas_z = np.pi*(r[1:]**2-r[:-1]**2)
    areas_r = 2*np.pi*r*dz
    V = areas_z*dz
    T = np.full((NZ, NR), T_INICIAL)
    curvas_t, curvas_f, curvas_c = [], [], []
    llegadas = {float(obj): None for obj in OBJETIVOS}
    mapa_llegada = None
    # Guardamos tres estados adicionales sin modificar el avance del solver.
    instantaneas = {12.0: None, 24.0: None, 36.0: None}
    pasos = int(DURACION_H*3600/DT)
    for n in range(pasos+1):
        t = n*DT
        if n % max(1, int(300/DT)) == 0:
            curvas_t.append(t/3600)
            curvas_f.append(float(T.min()))
            curvas_c.append(float(T.max()))
        frio = float(T.min())
        for hora in instantaneas:
            if n == round(hora*3600/DT):
                instantaneas[hora] = T.copy()
        for obj in llegadas:
            if llegadas[obj] is None and frio >= obj:
                llegadas[obj] = t/3600
        if mapa_llegada is None and llegadas[float(OBJETIVO)] is not None:
            mapa_llegada = T.copy()
        if n == pasos:
            break
        Tg = gas(t)
        kr = radial_efectiva(ks, T, Tg)
        h = conveccion(Tg)
        # Conductancia en interfaces radiales: resistencia de medias celdas en serie
        kr_entre = 2/(1/kr[:, :-1]+1/kr[:, 1:])
        gr = kr_entre*areas_r[1:-1]/dr
        gz = ks*areas_z/dz
        # Gas -> centro de celda: conveccion y media celda conductiva en serie
        hr_in = 1/(1/h+dr/(2*kr[:, 0]))
        hr_out = 1/(1/h+dr/(2*kr[:, -1]))
        hz = 1/(1/h+dz/(2*ks))
        # Comprobacion conservadora de estabilidad explicita en cada celda
        G = np.zeros_like(T)
        G[:, :-1] += gr
        G[:, 1:] += gr
        G[:-1, :] += gz
        G[1:, :] += gz
        G[:, 0] += hr_in*areas_r[0]
        G[:, -1] += hr_out*areas_r[-1]
        G[0, :] += hz*areas_z
        G[-1, :] += hz*areas_z
        limite = np.min(rho*cp*V[None, :]/G)
        if DT >= 0.9*limite:
            raise ValueError(f'DT={DT} s demasiado grande; usar menos de {0.9*limite:.2f} s')
        Q = np.zeros_like(T)
        fr = gr*(T[:, 1:]-T[:, :-1])
        Q[:, :-1] += fr
        Q[:, 1:] -= fr
        fz = gz[None, :]*(T[1:, :]-T[:-1, :])
        Q[:-1, :] += fz
        Q[1:, :] -= fz
        Q[:, 0] += hr_in*areas_r[0]*(Tg-T[:, 0])
        Q[:, -1] += hr_out*areas_r[-1]*(Tg-T[:, -1])
        Q[0, :] += hz*areas_z*(Tg-T[0, :])
        Q[-1, :] += hz*areas_z*(Tg-T[-1, :])
        T = T + DT*Q/(rho*cp*V[None, :])
    return dict(t=np.array(curvas_t), frio=np.array(curvas_f),
                caliente=np.array(curvas_c), llegadas=llegadas, mapa=mapa_llegada,
                instantaneas=instantaneas, r=r)


def main():
    print('Datos Ternium: SAE 1006 / SAE 1010; diámetro interior 508 mm; diámetro exterior máximo 1829 mm.')
    print(f'Geometría común Excel: {MATERIAL_REFERENCIA} ({FAMILIA_REFERENCIA}/{GRADO_REFERENCIA}), '
          f'ancho {ALTURA*1000:.0f} mm, espesor {ESPESOR_LAMINA*1000:.2f} mm; '
          'la fila no identifica ninguno de los dos grados SAE.')
    print(f'Horno programado {TEMP_HORNO_PROGRAMADA_F:g} °F; gas reportado fuera de contacto '
          f'{TEMP_SAT_GAS_F:g} °F = {T_GAS_MAX:g} °C; contacto aislado {TEMP_CONTACTO_F:g} °F '
          f'= {(TEMP_CONTACTO_F-32)*5/9:g} °C; caudal total {CAUDAL_TOTAL_M3_S:.2f} m³/s.')
    print('SUPUESTOS ACTIVOS: propiedades térmicas bibliográficas constantes; diámetro exterior máximo; '
          'rampa de gas de 12 h, meseta aplicada a la frontera, temperatura inicial, '
          'contacto entre láminas y parámetros de convección locales. No hay calibración experimental.')
    resultados = {nombre: simular(a) for nombre, a in ACEROS.items()}

    # Curvas comparativas: punto frío, punto caliente y frontera hipotética de gas.
    fig, ax = plt.subplots(figsize=(10, 5))
    for nombre, x in resultados.items():
        linea, = ax.plot(x['t'], x['frio'], lw=2, label=f'{nombre}: punto frío')
        ax.plot(x['t'], x['caliente'], '--', color=linea.get_color(), alpha=.55,
                label=f'{nombre}: punto caliente')
    tt = next(iter(resultados.values()))['t']
    ax.plot(tt, [gas(v*3600) for v in tt], ':', color='black', label='Gas (escenario)')
    ax.axhline(OBJETIVO, color='gray', ls='-.', label=f'Objetivo {OBJETIVO:g} °C')
    ax.set(xlabel='Tiempo (h)', ylabel='Temperatura (°C)',
           title='Calentamiento comparativo: SAE 1006 y SAE 1010', xlim=(0, DURACION_H))
    ax.legend(fontsize=8); ax.grid(alpha=.3); fig.tight_layout()
    fig.savefig('ternium_curvas_sae.png', dpi=160)
    plt.show()

    # Tiempo de primer cruce del punto frío para cada objetivo.
    fig, ax = plt.subplots(figsize=(10, 5))
    for nombre, x in resultados.items():
        tiempos = [np.nan if x['llegadas'][float(o)] is None else x['llegadas'][float(o)]
                   for o in OBJETIVOS]
        ax.plot(OBJETIVOS, tiempos, '-o', lw=2, label=nombre)
    ax.axvline(OBJETIVO, color='gray', ls=':', label=f'Referencia {OBJETIVO:g} °C')
    ax.set(xlabel='Temperatura objetivo (°C)', ylabel='Tiempo de llegada del punto frío (h)',
           title='Tiempo de calentamiento según el objetivo')
    ax.grid(alpha=.3); ax.legend(); fig.tight_layout()
    fig.savefig('ternium_tiempos_objetivo_sae.png', dpi=160)
    plt.show()

    # Mapas a tiempos de cruce distintos para cada grado; mismo rango cromático.
    fig, axes = plt.subplots(2, 1, figsize=(9, 10), sharex=True, sharey=True)
    for ax, (nombre, x) in zip(axes, resultados.items()):
        if x['mapa'] is None:
            ax.text(.5, .5, 'El punto frío no alcanzó el objetivo', ha='center', va='center',
                    transform=ax.transAxes)
            continue
        rr = x['r']; zz = np.linspace(0, ALTURA, NZ+1)
        im = ax.pcolormesh(rr, zz, x['mapa'], vmin=OBJETIVO, vmax=T_GAS_MAX,
                           cmap='YlOrBr_r', shading='flat')
        ax.pcolormesh(-rr[::-1], zz, x['mapa'][:, ::-1], vmin=OBJETIVO, vmax=T_GAS_MAX,
                      cmap='YlOrBr_r', shading='flat')
        ax.set(title=f'{nombre}: {x["llegadas"][float(OBJETIVO)]:.2f} h',
               ylabel='Altura (m)')
        ax.set_aspect('equal')
    axes[-1].set_xlabel('Posición horizontal (m)')
    if any(x['mapa'] is not None for x in resultados.values()):
        fig.colorbar(im, ax=axes, label='Temperatura (°C)', shrink=.8)
    fig.suptitle(f'Mapas al alcanzar {OBJETIVO:g} °C en el punto frío; hueco central en blanco')
    fig.savefig('ternium_mapas_objetivo_sae.png', dpi=160, bbox_inches='tight')
    plt.show()

    # Mapas comparables en tres instantes, con la misma escala cromatica (25 a 685 C).
    fig, axes = plt.subplots(2, 3, figsize=(12, 6.2), sharex=True, sharey=True)
    for row, (nombre, x) in enumerate(resultados.items()):
        for col, (hora, field) in enumerate(x['instantaneas'].items()):
            ax = axes[row, col]
            rr = x['r']; zz = np.linspace(0, ALTURA, NZ+1)
            im2 = ax.pcolormesh(rr, zz, field, vmin=T_INICIAL,
                                vmax=T_GAS_MAX, cmap='inferno', shading='flat')
            ax.pcolormesh(-rr[::-1], zz, field[:, ::-1], vmin=T_INICIAL,
                          vmax=T_GAS_MAX, cmap='inferno', shading='flat')
            ax.set_aspect('equal')
            ax.set_title(f'{nombre}; t={hora:.0f} h')
            if col == 0:
                ax.set_ylabel('Altura (m)')
            if row == 1:
                ax.set_xlabel('Posición horizontal (m)')
    fig.suptitle('Evolución radial--axial del calentamiento (escala común)', y=.99)
    fig.subplots_adjust(left=.06, right=.88, top=.90, bottom=.12, wspace=.20, hspace=.30)
    cax = fig.add_axes([.905, .20, .014, .58])
    fig.colorbar(im2, cax=cax, label='Temperatura (°C)')
    fig.savefig('ternium_mapas_evolucion_sae.png', dpi=180, bbox_inches='tight')
    plt.show()

    # Diferencia entre puntos frios al mismo instante; separa curvas casi superpuestas.
    fig, ax = plt.subplots(figsize=(10, 4))
    n1006, n1010 = 'SAE 1006', 'SAE 1010'
    ax.plot(resultados[n1006]['t'],
            resultados[n1010]['frio'] - resultados[n1006]['frio'],
            color='#6a4b7d', linewidth=2)
    ax.axhline(0, color='black', linewidth=.7)
    ax.set(xlabel='Tiempo (h)', ylabel='T mínimo (1010) - T mínimo (1006) (°C)',
           title='Diferencia temporal de temperatura en el punto frío')
    ax.grid(alpha=.3)
    fig.tight_layout()
    fig.savefig('ternium_diferencia_punto_frio.png', dpi=180)
    plt.show()

    print('\nResultados de escenario (h; no son tiempos de planta):')
    print('Objetivo °C | ' + ' | '.join(ACEROS))
    for obj in OBJETIVOS:
        def valor(nombre):
            t = resultados[nombre]['llegadas'][float(obj)]
            return f'{t:.2f}' if t is not None else f'no alcanzado en {DURACION_H:g} h'
        print(f'{obj:10.0f} | ' + ' | '.join(valor(n) for n in ACEROS))
    for nombre, a in ACEROS.items():
        print(f'{nombre}: alfa axial = {a["ks"]/(a["rho"]*a["cp"]):.3e} m²/s '
              '(propiedades bibliográficas constantes).')
    print('Los 635 °C de contacto no validan estos tiempos: falta instante y termopares independientes.')


if __name__ == '__main__':
    main()